#!/usr/bin/env node
// Regenerates src/chain/abi.ts from the Foundry build output (run after changing the contracts):
//   (cd ../contracts && forge build) && node scripts/sync-abis.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const out = `${root}../contracts/out`;
const contracts = { novaTokenAbi: 'NovaToken', novaGarageAbi: 'NovaGarage', novaArenaAbi: 'NovaArena' };

let ts = '/** GENERATED by scripts/sync-abis.mjs from contracts/out — do not edit. */\n';
for (const [name, c] of Object.entries(contracts)) {
  const { abi } = JSON.parse(readFileSync(`${out}/${c}.sol/${c}.json`, 'utf8'));
  ts += `\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
writeFileSync(`${root}src/chain/abi.ts`, ts);
console.log(`wrote src/chain/abi.ts (${Object.values(contracts).join(', ')})`);
