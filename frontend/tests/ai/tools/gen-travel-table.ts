/**
 * Generates src/ai/travelTable.ts: measured arrival times of the bots' Driver in the real sim, over a grid of
 * (start forward speed × target angle × target distance × boost). Re-run after changing car physics or the Driver:
 *
 *   npx rolldown tests/ai/tools/gen-travel-table.ts --file <tmp>/gen.mjs --format esm --platform node && node <tmp>/gen.mjs
 *
 * (tests/ai/travelTable.test.ts re-simulates random grid points and fails if the table is stale.)
 */
import { writeFileSync } from 'node:fs';
import { Driver, DRIVE_DEFAULT } from '../../../src/ai/controller';
import { SKILLS } from '../../../src/ai/difficulty';
import { CONTACT_REACH } from '../../../src/ai/intercept';
import { TT_A, TT_B, TT_D, TT_V } from '../../../src/ai/travelGrid';
import { makeControlState } from '../../../src/sim/types';
import { freePlayWorld, info, place } from '../helpers';

export function measure(v0: number, angDeg: number, d: number, boost: number): number {
  const w = freePlayWorld();
  // start well inside the field so every target is reachable without walls
  const car = place(w, 0, 0, 0, 0, 1, v0, boost);
  const a = (angDeg * Math.PI) / 180;
  const tx = -Math.sin(a) * d;
  const tz = Math.cos(a) * d;
  const ci = info(w, 0);
  const drv = new Driver(SKILLS.legend);
  const c = makeControlState();
  for (let i = 0; i < 120 * 10; i++) {
    info(w, 0, ci);
    drv.drive(ci, tx, 0, tz, 23, c, { ...DRIVE_DEFAULT });
    w.step([c]);
    if (Math.hypot(car.pos.x - tx, car.pos.z - tz) < CONTACT_REACH) return (i + 1) / 120;
  }
  return 10;
}

const isMain = typeof process !== 'undefined' && !!process.argv[1] && /gen-travel-table|gen\.mjs$/.test(process.argv[1]);
if (isMain) {
  const data: number[] = [];
  for (const b of TT_B) for (const v of TT_V) for (const a of TT_A) for (const d of TT_D) data.push(measure(v, a, d, b));
  const body = data.map((x) => x.toFixed(3).replace(/\.?0+$/, '')).join(',');
  const src = `/**
 * NOVABALL AI — GENERATED by tests/ai/tools/gen-travel-table.ts (do not edit by hand).
 * Measured Driver arrival times (s) in the real sim; index ((b · nV + v) · nA + a) · nD + d over travelGrid.ts.
 */
export const TT_DATA = new Float32Array([${body}]);
`;
  // run from the project root
  const out = `${process.cwd()}/src/ai/travelTable.ts`;
  writeFileSync(out, src);
  console.log(`wrote ${data.length} entries to ${out}`);
}
